def detect_disease(complaint_text: str):
    if not complaint_text:
        return None, []
    matches = []
    for disease, keywords in DISEASE_KEYWORDS.items():
        for kw in keywords:
            if kw in complaint_text:
                matches.append(disease)
                break
    return (matches[0] if matches else None), matches
